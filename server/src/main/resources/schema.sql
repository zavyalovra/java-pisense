-- ============================================================
-- ENUM-типы (идемпотентно через DO-блок)
-- ============================================================
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type t
    JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'sensor_status' AND n.nspname = current_schema()
  ) THEN
    CREATE TYPE sensor_status AS ENUM (
      'DISCOVERED', 'ACTIVE', 'TEMPORARILY_UNAVAILABLE', 'DISABLED', 'RETIRED'
    );
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM pg_type t
    JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'batch_status' AND n.nspname = current_schema()
  ) THEN
    CREATE TYPE batch_status AS ENUM ('ACCEPTED', 'REJECTED');
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM pg_type t
    JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'bus_type' AND n.nspname = current_schema()
  ) THEN
    CREATE TYPE bus_type AS ENUM ('I2C', 'SPI', 'ONEWIRE');
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM pg_type t
    JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'sensor_type' AND n.nspname = current_schema()
  ) THEN
    CREATE TYPE sensor_type AS ENUM ('TEMPERATURE', 'PRESSURE', 'HUMIDITY', 'ILLUMINANCE');
  END IF;
END
$$;


-- ============================================================
-- bridges
-- ============================================================
CREATE TABLE IF NOT EXISTS bridges (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  external_id varchar(100) NOT NULL,
  name        varchar(255),
  active      boolean      NOT NULL DEFAULT true,
  created_at  timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ux_bridges_external_id UNIQUE (external_id)
);


-- ============================================================
-- buses
-- ============================================================
CREATE TABLE IF NOT EXISTS buses (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bridge_id   bigint   NOT NULL,
  external_id varchar(100) NOT NULL,
  bus_type    bus_type NOT NULL,
  CONSTRAINT ux_buses_bridge_external_id UNIQUE (bridge_id, external_id),
  CONSTRAINT fk_buses_bridge
    FOREIGN KEY (bridge_id) REFERENCES bridges (id)
    ON DELETE RESTRICT
    DEFERRABLE INITIALLY IMMEDIATE
);


-- ============================================================
-- measurement_classes
-- ============================================================
CREATE TABLE IF NOT EXISTS measurement_classes (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type_code           sensor_type NOT NULL,
  unit_of_measurement varchar(50) NOT NULL,
  description         varchar(255) NOT NULL
);


-- ============================================================
-- locations
-- ============================================================
CREATE TABLE IF NOT EXISTS locations (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        varchar(100) NOT NULL,
  description varchar(255) NOT NULL
);


-- ============================================================
-- sensors
-- ============================================================
CREATE TABLE IF NOT EXISTS sensors (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bus_id               bigint        NOT NULL,
  address              varchar(100)  NOT NULL,
  model                varchar(255),
  serial_number        varchar(255),
  measurement_class_id bigint        NOT NULL,
  location_id          bigint,
  status               sensor_status NOT NULL DEFAULT 'DISCOVERED',
  created_at           timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_seen_at         timestamptz,
  CONSTRAINT ux_sensors_bus_address UNIQUE (bus_id, address),
  CONSTRAINT fk_sensors_bus
    FOREIGN KEY (bus_id) REFERENCES buses (id)
    ON DELETE RESTRICT
    DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT fk_sensors_measurement_class
    FOREIGN KEY (measurement_class_id) REFERENCES measurement_classes (id)
    ON DELETE RESTRICT
    DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT fk_sensors_location
    FOREIGN KEY (location_id) REFERENCES locations (id)
    ON DELETE RESTRICT
    DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX IF NOT EXISTS ix_sensors_serial_number
  ON sensors (serial_number);

CREATE INDEX IF NOT EXISTS ix_sensors_status
  ON sensors (status);


-- ============================================================
-- measurement_batches
-- ============================================================
CREATE TABLE IF NOT EXISTS measurement_batches (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id    uuid         NOT NULL,
  status      batch_status NOT NULL DEFAULT 'ACCEPTED',
  measured_at timestamptz,
  received_at timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ux_measurement_batches_batch_id UNIQUE (batch_id)
);


-- ============================================================
-- measurements
-- ============================================================
CREATE TABLE IF NOT EXISTS measurements (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  measurement_id       uuid    NOT NULL,
  measurement_batch_id bigint  NOT NULL,
  sensor_id            bigint  NOT NULL,
  measurement_value    double precision NOT NULL,
  measured_at          timestamptz NOT NULL,
  received_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ux_measurements_measurement_id UNIQUE (measurement_id),
  CONSTRAINT fk_measurements_batch
    FOREIGN KEY (measurement_batch_id) REFERENCES measurement_batches (id)
    ON DELETE CASCADE
    DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT fk_measurements_sensor
    FOREIGN KEY (sensor_id) REFERENCES sensors (id)
    ON DELETE RESTRICT
    DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX IF NOT EXISTS ix_measurements_sensor_measured_at
  ON measurements (sensor_id, measured_at);

CREATE INDEX IF NOT EXISTS ix_measurements_measured_at
  ON measurements (measured_at);

CREATE INDEX IF NOT EXISTS ix_measurements_batch
  ON measurements (measurement_batch_id);


-- ============================================================
-- Комментарии (идемпотентны по своей природе)
-- ============================================================
COMMENT ON COLUMN bridges.external_id IS 'Стабильный идентификатор Raspberry Pi';
COMMENT ON COLUMN buses.external_id IS 'Например: i2c1, spi0';
COMMENT ON COLUMN buses.bus_type IS 'I2C, SPI и т.д.';
COMMENT ON COLUMN measurement_classes.unit_of_measurement IS 'Например: °C, %, Pa';
COMMENT ON COLUMN sensors.address IS 'Например: 0x76';
COMMENT ON COLUMN measurement_batches.batch_id IS 'Идентификатор batch, созданный bridge';
COMMENT ON COLUMN measurements.measurement_id IS 'Уникальный идентификатор измерения';
