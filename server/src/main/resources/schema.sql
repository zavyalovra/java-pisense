CREATE TABLE IF NOT EXISTS sensor_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(100) UNIQUE NOT NULL,
    unit VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS sensors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    type_id BIGINT NOT NULL,
    bus_type VARCHAR(100) NOT NULL,
    bus_address VARCHAR(100) NOT NULL,
    enabled boolean NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_sensors_sensor_types FOREIGN KEY (type_id) REFERENCES sensor_types(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS measurements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id BIGINT NOT NULL,
    value DOUBLE PRECISION NOT NULL,
    measured_at TIMESTAMP NOT NULL,
    received_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_measure UNIQUE (sensor_id, measured_at),
    CONSTRAINT fk_measurements_sensors FOREIGN KEY (sensor_id) REFERENCES sensors(id) ON DELETE CASCADE
);