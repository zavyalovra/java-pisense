-- ============================================================
-- PiSense — схема БД v3 (PostgreSQL 10+)
-- Скрипт идемпотентен: можно выполнять повторно.
-- Enum-подобные поля и справочные значения хранятся в varchar.
-- ============================================================

-- ------------------------------------------------------------
-- Мосты и шины
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS bridges (
    id           bigint       GENERATED BY DEFAULT AS IDENTITY,
    name         varchar(100) NOT NULL,
    status       varchar(30)  NOT NULL DEFAULT 'DISCOVERED',   -- DISCOVERED | ACTIVE | DISABLED
    created_at   timestamptz  NOT NULL DEFAULT now(),
    last_seen_at timestamptz,
    CONSTRAINT pk_bridges      PRIMARY KEY (id),
    CONSTRAINT ux_bridges_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS buses (
    id        bigint      GENERATED BY DEFAULT AS IDENTITY,
    bridge_id bigint      NOT NULL,
    name      varchar(50) NOT NULL,                            -- i2c1, i2c2, spi0, onewire ...
    CONSTRAINT pk_buses             PRIMARY KEY (id),
    CONSTRAINT ux_buses_bridge_name UNIQUE (bridge_id, name),
    CONSTRAINT fk_buses_bridge      FOREIGN KEY (bridge_id) REFERENCES bridges (id) ON DELETE CASCADE
);

-- ------------------------------------------------------------
-- Датчики и каналы
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sensors (
    id            bigint       GENERATED BY DEFAULT AS IDENTITY,
    bus_id        bigint       NOT NULL,
    sensor_code   varchar(100) NOT NULL,                       -- TelemetryDto.sensorId
    address       varchar(50),
    model         varchar(100),
    serial_number varchar(100),
    location      varchar(100),
    created_at    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_sensors                 PRIMARY KEY (id),
    CONSTRAINT ux_sensors_bus_sensor_code UNIQUE (bus_id, sensor_code),
    CONSTRAINT fk_sensors_bus             FOREIGN KEY (bus_id) REFERENCES buses (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS sensor_channels (
    id          bigint      GENERATED BY DEFAULT AS IDENTITY,
    sensor_id   bigint      NOT NULL,
    name        varchar(50) NOT NULL,                          -- channel-name: temperature, pressure ...
    metric_type varchar(30),                                   -- TEMPERATURE | PRESSURE | HUMIDITY | ILLUMINANCE ...
    unit        varchar(20),                                   -- Celsius, degF, hPa, %
    CONSTRAINT pk_sensor_channels             PRIMARY KEY (id),
    CONSTRAINT ux_sensor_channels_sensor_name UNIQUE (sensor_id, name),
    CONSTRAINT fk_sensor_channels_sensor      FOREIGN KEY (sensor_id) REFERENCES sensors (id) ON DELETE CASCADE
);

-- ------------------------------------------------------------
-- Посылки и измерения
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS batches (
    id           bigint      GENERATED BY DEFAULT AS IDENTITY,
    uuid         uuid        NOT NULL,                         -- генерируется на bridge, ключ идемпотентности
    bridge_id    bigint      NOT NULL,
    collected_at timestamptz NOT NULL,                         -- время опроса на bridge
    received_at  timestamptz NOT NULL DEFAULT now(),           -- время приёма сервером
    CONSTRAINT pk_batches        PRIMARY KEY (id),
    CONSTRAINT ux_batches_uuid   UNIQUE (uuid),
    CONSTRAINT fk_batches_bridge FOREIGN KEY (bridge_id) REFERENCES bridges (id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS measurements (
    id                  bigint           GENERATED BY DEFAULT AS IDENTITY,
    batch_id            bigint           NOT NULL,
    channel_id          bigint           NOT NULL,
    measurement_value   double precision NOT NULL,
    measured_at         timestamptz      NOT NULL,
    CONSTRAINT pk_measurements               PRIMARY KEY (id),
    CONSTRAINT ux_measurements_batch_channel UNIQUE (batch_id, channel_id),
    CONSTRAINT fk_measurements_batch         FOREIGN KEY (batch_id)   REFERENCES batches (id)         ON DELETE CASCADE,
    CONSTRAINT fk_measurements_channel       FOREIGN KEY (channel_id) REFERENCES sensor_channels (id) ON DELETE RESTRICT
);

-- ------------------------------------------------------------
-- Индексы
-- ------------------------------------------------------------
CREATE INDEX IF NOT EXISTS ix_batches_bridge_collected_at      ON batches (bridge_id, collected_at);
CREATE INDEX IF NOT EXISTS ix_measurements_channel_measured_at ON measurements (channel_id, measured_at);
