-- ============================================================
-- PiSense schema v2 (PostgreSQL 10+)
-- Без нативных ENUM-типов: значения хранятся как varchar(100),
-- допустимые значения контролируются CHECK-ограничениями.
-- Скрипт идемпотентен (CREATE ... IF NOT EXISTS) и не содержит
-- DO-блоков с $$, поэтому корректно выполняется через spring.sql.init.
-- ============================================================

-- ============================================================
-- measurement_classes
-- ============================================================
CREATE TABLE IF NOT EXISTS measurement_classes (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type_code           varchar(100) NOT NULL,
  unit_of_measurement varchar(50)  NOT NULL,
  description         varchar(255) NOT NULL,
  CONSTRAINT ck_measurement_classes_type_code
    CHECK (type_code IN ('TEMPERATURE', 'PRESSURE', 'HUMIDITY', 'ILLUMINANCE'))
);


-- ============================================================
-- locations
-- ============================================================
CREATE TABLE IF NOT EXISTS locations (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        varchar(100) NOT NULL,
  description varchar(255) NOT NULL
);


-- ============================================================
-- sensors
-- ============================================================
CREATE TABLE IF NOT EXISTS sensors (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  address              varchar(100)  NOT NULL,
  model                varchar(255),
  serial_number        varchar(255),
  measurement_class_id bigint        NOT NULL,
  location_id          bigint,
  status               varchar(100)  NOT NULL DEFAULT 'DISCOVERED',
  created_at           timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_seen_at         timestamptz,
  CONSTRAINT ck_sensors_status
    CHECK (status IN ('DISCOVERED', 'ACTIVE', 'TEMPORARILY_UNAVAILABLE', 'DISABLED', 'RETIRED')),
  CONSTRAINT fk_sensors_measurement_class
    FOREIGN KEY (measurement_class_id) REFERENCES measurement_classes (id)
    ON DELETE RESTRICT
    DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT fk_sensors_location
    FOREIGN KEY (location_id) REFERENCES locations (id)
    ON DELETE RESTRICT
    DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX IF NOT EXISTS ix_sensors_serial_number
  ON sensors (address);

CREATE INDEX IF NOT EXISTS ix_sensors_status
  ON sensors (status);


-- ============================================================
-- batches
-- ============================================================
CREATE TABLE IF NOT EXISTS batches (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid        uuid         NOT NULL,
  status      varchar(100) NOT NULL DEFAULT 'ACCEPTED',
  measured_at timestamptz,
  received_at timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ux_batches_uuid UNIQUE (uuid),
  CONSTRAINT ck_batches_status
    CHECK (status IN ('ACCEPTED', 'REJECTED'))
);


-- ============================================================
-- measurements
-- ============================================================
CREATE TABLE IF NOT EXISTS measurements (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid                 uuid    NOT NULL,
  batch_id             bigint  NOT NULL,
  sensor_id            bigint  NOT NULL,
  measurement_value    double precision NOT NULL,
  measured_at          timestamptz NOT NULL,
  received_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ux_measurements_uuid UNIQUE (uuid),
  CONSTRAINT fk_measurements_batch
    FOREIGN KEY (batch_id) REFERENCES batches (id)
    ON DELETE CASCADE
    DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT fk_measurements_sensor
    FOREIGN KEY (sensor_id) REFERENCES sensors (id)
    ON DELETE RESTRICT
    DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX IF NOT EXISTS ix_measurements_sensor_measured_at
  ON measurements (sensor_id, measured_at);

CREATE INDEX IF NOT EXISTS ix_measurements_measured_at
  ON measurements (measured_at);

CREATE INDEX IF NOT EXISTS ix_measurements_batch
  ON measurements (batch_id);
