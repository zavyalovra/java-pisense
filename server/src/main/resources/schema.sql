-- ============================================================
-- PiSense schema v2 (PostgreSQL 10+)
-- допустимые значения контролируются CHECK-ограничениями.
-- Скрипт идемпотентен (CREATE ... IF NOT EXISTS)
-- ============================================================

-- ============================================================
-- measurement_classes
-- ============================================================
CREATE TABLE IF NOT EXISTS measurement_classes (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type_code           varchar(100) NOT NULL,
  unit_of_measurement varchar(50)  NOT NULL,
  description         varchar(255) NOT NULL,
  CONSTRAINT ck_measurement_classes_type_code
    CHECK (type_code IN ('TEMPERATURE', 'PRESSURE', 'HUMIDITY', 'ILLUMINANCE'))
);


-- ============================================================
-- locations
-- ============================================================
CREATE TABLE IF NOT EXISTS locations (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        varchar(100) NOT NULL,
  description varchar(255) NOT NULL
);

-- ============================================================
-- bridges
-- ============================================================
CREATE TABLE IF NOT EXISTS bridges (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bridge_name          varchar(100) NOT NULL,
  status               varchar(100)  NOT NULL DEFAULT 'DISCOVERED',
  created_at           timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_seen_at         timestamptz,
  CONSTRAINT ux_bridges_bridge_name UNIQUE (bridge_name),
  CONSTRAINT ck_bridges_status
      CHECK (status IN ('DISCOVERED', 'ACTIVE', 'TEMPORARILY_UNAVAILABLE', 'DISABLED', 'RETIRED'))
);

-- ============================================================
-- bus
-- ============================================================
CREATE TABLE IF NOT EXISTS buses (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bus_name             varchar(100) NOT NULL,
  bridge_id            bigint       NOT NULL,
  CONSTRAINT ux_buses_bridge_bus_name
      UNIQUE (bridge_id, bus_name),
  CONSTRAINT fk_bus_bridge
    FOREIGN KEY (bridge_id) REFERENCES bridges (id) ON DELETE CASCADE
);

-- ============================================================
-- sensors
-- ============================================================
CREATE TABLE IF NOT EXISTS sensors (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bus_id               bigint        NOT NULL,
  address              varchar(100)  NOT NULL,
  model                varchar(255),
  serial_number        varchar(255),
  location_id          bigint,
  status               varchar(100)  NOT NULL DEFAULT 'DISCOVERED',
  created_at           timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_seen_at         timestamptz,
  CONSTRAINT ck_sensors_status
    CHECK (status IN ('DISCOVERED', 'ACTIVE', 'TEMPORARILY_UNAVAILABLE', 'DISABLED', 'RETIRED')),
  CONSTRAINT ux_sensors_bus_address
    UNIQUE (bus_id, address),
  CONSTRAINT fk_sensors_buses
    FOREIGN KEY (bus_id) REFERENCES buses (id) ON DELETE CASCADE,
  CONSTRAINT fk_sensors_locations
    FOREIGN KEY (location_id) REFERENCES locations (id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS ix_sensors_address
  ON sensors (address);

CREATE INDEX IF NOT EXISTS ix_sensors_status
  ON sensors (status);

-- ============================================================
-- sensor_channels
-- ============================================================
CREATE TABLE IF NOT EXISTS sensor_channels (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sensor_id            bigint NOT NULL REFERENCES sensors (id) ON DELETE CASCADE,
  hardware_channel     varchar(50) NOT NULL,       -- 'temperature', 'pressure', 'humidity'
  sensor_type          varchar(50) NOT NULL,
  measurement_class_id bigint,
  CONSTRAINT ux_sensor_channels_sensor_hardware_channel UNIQUE (sensor_id, hardware_channel),
  CONSTRAINT ck_sensor_channels_sensor_type
    CHECK (sensor_type IN ('TEMPERATURE', 'PRESSURE', 'HUMIDITY', 'ILLUMINANCE')),
  CONSTRAINT fk_sensor_channels_measurement_class
    FOREIGN KEY (measurement_class_id) REFERENCES measurement_classes (id) ON DELETE RESTRICT
);

-- ============================================================
-- batches
-- ============================================================
CREATE TABLE IF NOT EXISTS batches (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid        uuid         NOT NULL,
  status      varchar(100) NOT NULL DEFAULT 'ACCEPTED',
  measured_at timestamptz,
  received_at timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ux_batches_uuid UNIQUE (uuid),
  CONSTRAINT ck_batches_status
    CHECK (status IN ('ACCEPTED', 'REJECTED'))
);


-- ============================================================
-- measurements
-- ============================================================
CREATE TABLE IF NOT EXISTS measurements (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid                 uuid    NOT NULL,
  batch_id             bigint  NOT NULL,
  channel_id           bigint  NOT NULL,
  measurement_value    double precision NOT NULL,
  measured_at          timestamptz NOT NULL,
  received_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ux_measurements_uuid UNIQUE (uuid),
  CONSTRAINT fk_measurements_batch
    FOREIGN KEY (batch_id) REFERENCES batches (id) ON DELETE CASCADE,
  CONSTRAINT fk_measurements_channel
    FOREIGN KEY (channel_id) REFERENCES sensor_channels (id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS ix_measurements_channel_measured_at
  ON measurements (channel_id, measured_at);

CREATE INDEX IF NOT EXISTS ix_measurements_measured_at
  ON measurements (measured_at);

CREATE INDEX IF NOT EXISTS ix_measurements_batch
  ON measurements (batch_id);